/*
   Create tables for the weblists application. The schema is simple, with a table 
   for items, lists, and their many-to-many join.
 */

SET search_path TO weblists;

/* 1) Create the tables */
CREATE TABLE list (
        uuid        VARCHAR(36) NOT NULL PRIMARY KEY,
        create_date TIMESTAMP  NOT NULL DEFAULT CURRENT_TIMESTAMP,
        name        VARCHAR(200),
        description VARCHAR(4000)
);

COMMENT ON TABLE list IS 'A list. This is the central table from which everything else branches.';
COMMENT ON COLUMN list.uuid IS 'A full (RFC 4122) UUID stored as a string. Definitely want to store as UUID but for now let''s just make things work alike.';
COMMENT ON COLUMN list.create_date IS 'The date this list was created. Immutable.';
COMMENT ON COLUMN list.name IS 'The name of the list. USER-INPUTTED THEREFORE UNSAFE.';
COMMENT ON COLUMN list.description IS 'A description of this list. USER-INPUTTED THEREFORE UNSAFE.';

CREATE TABLE item (
        id          INTEGER NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
        name        VARCHAR(200) NOT NULL,
        description VARCHAR(4000)
);

COMMENT ON TABLE item IS 'An item. Items are added to lists.';
COMMENT ON COLUMN item.id IS 'Plain PK. Maybe do user-specific items later.';
COMMENT ON COLUMN item.name IS 'The item''s name. USER-INPUTTED THEREFORE UNSAFE.';
COMMENT ON COLUMN item.description IS 'A description of this item. USER-INPUTTED THEREFORE UNSAFE.';

CREATE TABLE list_item (
        list_uuid     VARCHAR(36) NOT NULL,
        item_id       INTEGER NOT NULL,
        sort_idx      INTEGER NOT NULL DEFAULT 0,
        quantity      INTEGER,
        quantity_unit VARCHAR(20),
        marked        BOOLEAN NOT NULL DEFAULT FALSE,

        FOREIGN KEY (list_uuid) REFERENCES list(uuid),
        FOREIGN KEY (item_id)   REFERENCES item(id)
);

COMMENT ON TABLE list_item IS 'An item in a list.';
COMMENT ON COLUMN list_item.sort_idx IS 'The item''s order in the list. Updated by in-app logic.';
COMMENT ON COLUMN list_item.quantity IS 'The item count.';
COMMENT ON COLUMN list_item.quantity_unit IS 'The item count units (eg: "count", "dozen", "gallon", "oz", "kg"). USER-INPUTTED THEREFORE UNSAFE.';
COMMENT ON COLUMN list_item.marked IS 'Whether or not this item is "marked". May change this to a dictionary if we want to mark items in different ways.';

